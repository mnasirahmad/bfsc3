export function printReportDirect(options: {
  title: string;
  htmlContent: string;
  landscape?: boolean;
}): void {
  const { title, htmlContent, landscape = false } = options;
  const oldActive = document.getElementById('printable-active-report');
  if (oldActive) oldActive.remove();

  const container = document.createElement('div');
  container.id = 'printable-active-report';
  container.className = 'printable-report-container';

  const styleTag = `
    <style>
      @page {
        size: letter ${landscape ? 'landscape' : 'portrait'};
        margin: 10mm;
      }
      * {
        box-sizing: border-box;
      }
      .printable-report-container {
        font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, "Helvetica Neue", Arial, sans-serif;
        font-size: 11px;
        color: #111827;
        background: #ffffff;
        width: 100%;
        min-height: 255mm;
        display: flex;
        flex-direction: column;
        justify-content: space-between;
        line-height: 1.35;
      }
      table {
        width: 100%;
        border-collapse: collapse;
        margin-top: 8px;
        font-size: 10.5px;
      }
      th {
        background-color: #064e3b !important;
        color: #ffffff !important;
        -webkit-print-color-adjust: exact;
        print-color-adjust: exact;
        font-weight: 700;
        text-transform: uppercase;
        font-size: 9.5px;
        letter-spacing: 0.3px;
        padding: 6px 8px;
        border: 1px solid #064e3b;
      }
      td {
        padding: 5px 8px;
        border: 1px solid #d1d5db;
        vertical-align: top;
      }
      tr:nth-child(even) {
        background-color: #f9fafb !important;
        -webkit-print-color-adjust: exact;
        print-color-adjust: exact;
      }
      tfoot td {
        background-color: #f3f4f6 !important;
        font-weight: bold;
        border-top: 2px solid #064e3b;
        -webkit-print-color-adjust: exact;
        print-color-adjust: exact;
      }
    </style>
  `;

  container.innerHTML = `${styleTag}${htmlContent}`;
  document.body.appendChild(container);
  document.body.classList.add('printing-report');
  const originalTitle = document.title;
  if (title) {
    document.title = title;
  }

  const cleanUp = () => {
    document.body.classList.remove('printing-report');
    if (document.title === title) {
      document.title = originalTitle;
    }
    const elem = document.getElementById('printable-active-report');
    if (elem) elem.remove();
    window.removeEventListener('afterprint', cleanUp);
  };

  window.addEventListener('afterprint', cleanUp);

  setTimeout(() => {
    try {
      window.print();
    } catch (err) {
      console.error('window.print failed:', err);
    }
    setTimeout(cleanUp, 3000);
  }, 100);
}

export async function downloadPdfFromReportHtml(options: {
  htmlContent: string;
  filename: string;
  landscape?: boolean;
}): Promise<void> {
  const { htmlContent, filename, landscape = false } = options;

  const container = document.createElement('div');
  container.style.position = 'fixed';
  container.style.left = '-9999px';
  container.style.top = '0';
  container.style.width = landscape ? '1120px' : '820px';
  container.style.background = '#ffffff';
  container.style.padding = '24px 28px';
  container.style.boxSizing = 'border-box';
  container.style.fontFamily = '-apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, "Helvetica Neue", Arial, sans-serif';
  container.style.color = '#111827';
  container.style.zIndex = '-1000';

  const styleTag = `
    <style>
      * { box-sizing: border-box; }
      table { width: 100%; border-collapse: collapse; margin-top: 8px; font-size: 11px; }
      th {
        background-color: #064e3b;
        color: #ffffff;
        font-weight: 700;
        text-transform: uppercase;
        font-size: 10px;
        padding: 7px 9px;
        border: 1px solid #064e3b;
      }
      td {
        padding: 6px 9px;
        border: 1px solid #d1d5db;
        vertical-align: top;
      }
      tr:nth-child(even) { background-color: #f9fafb; }
      tfoot td {
        background-color: #f3f4f6;
        font-weight: bold;
        border-top: 2px solid #064e3b;
      }
    </style>
  `;

  container.innerHTML = `${styleTag}${htmlContent}`;
  document.body.appendChild(container);

  try {
    const images = Array.from(container.getElementsByTagName('img'));
    await Promise.all(
      images.map(img => {
        if (img.complete) return Promise.resolve();
        return new Promise(resolve => {
          img.onload = resolve;
          img.onerror = resolve;
          setTimeout(resolve, 500);
        });
      })
    );

    const canvas = await html2canvas(container, {
      scale: 2,
      useCORS: true,
      backgroundColor: '#ffffff',
      windowWidth: landscape ? 1120 : 820
    });

    const pdf = new jsPDF({
      orientation: landscape ? 'landscape' : 'portrait',
      unit: 'mm',
      format: 'a4'
    });

    const pdfWidth = pdf.internal.pageSize.getWidth();
    const pdfHeight = pdf.internal.pageSize.getHeight();
    const imgWidth = pdfWidth;
    const imgHeight = (canvas.height * pdfWidth) / canvas.width;
    let heightLeft = imgHeight;
    let position = 0;

    const imgData = canvas.toDataURL('image/jpeg', 0.95);
    pdf.addImage(imgData, 'JPEG', 0, position, imgWidth, imgHeight, undefined, 'FAST');
    heightLeft -= pdfHeight;

    while (heightLeft > 2) {
      position -= pdfHeight;
      pdf.addPage();
      pdf.addImage(imgData, 'JPEG', 0, position, imgWidth, imgHeight, undefined, 'FAST');
      heightLeft -= pdfHeight;
    }

    const safeName = filename.endsWith('.pdf') ? filename : `${filename}.pdf`;
    pdf.save(safeName);
  } finally {
    container.remove();
  }
}
